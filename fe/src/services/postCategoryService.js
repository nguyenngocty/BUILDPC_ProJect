import api from "./api";

const ADMIN_API = "/admin/post-categories";

const postCategoryService = {
  // ============================================================
  // LIST
  // ============================================================

  getCategories: (params = {}) => {
    return api.get(ADMIN_API, {
      params,
    });
  },

  // ============================================================
  // ACTIVE
  // Dùng cho dropdown Post
  // ============================================================

  getActiveCategories: () => {
    return api.get(`${ADMIN_API}/active`);
  },

  // ============================================================
  // DETAIL
  // ============================================================

  getCategory: (id) => {
    return api.get(`${ADMIN_API}/${id}`);
  },

  // ============================================================
  // CREATE
  // ============================================================

  createCategory: (data) => {
    return api.post(ADMIN_API, data);
  },

  // ============================================================
  // UPDATE
  // ============================================================

  updateCategory: (id, data) => {
    return api.patch(`${ADMIN_API}/${id}`, data);
  },

  // ============================================================
  // STATUS
  // ============================================================

  toggleStatus: (id) => {
    return api.patch(`${ADMIN_API}/${id}/toggle-status`);
  },

  // ============================================================
  // DELETE
  // ============================================================

  deleteCategory: (id) => {
    return api.delete(`${ADMIN_API}/${id}`);
  },

  // ============================================================
  // TRASH
  // ============================================================

  getTrash: (params = {}) => {
    return api.get(`${ADMIN_API}/trash`, {
      params,
    });
  },

  // ============================================================
  // RESTORE
  // ============================================================

  restoreCategory: (id) => {
    return api.patch(`${ADMIN_API}/${id}/restore`);
  },
};

export default postCategoryService;
